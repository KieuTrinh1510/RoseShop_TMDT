String tr(String key, [Map<String, String>? args]) {
  final en = AppSettings.instance.language == 'en';
  var s = (en ? _en[key] : _vi[key]) ?? _vi[key] ?? key;
  args?.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

